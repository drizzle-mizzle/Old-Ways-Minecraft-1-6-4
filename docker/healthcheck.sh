#!/usr/bin/env bash
# Healthcheck: легаси server-list-ping протокола 1.6.4.
#
# Простой TCP-connect тоже показал бы, что порт занят, но ядро пишет на него
# "lost connection" каждые 30 секунд и засоряет лог. Настоящий ping тише
# и честнее: он проверяет, что сервер отвечает по протоколу, а не просто слушает.
#
# 0xFE 0x01 — запрос статуса. Ответ начинается с 0xFF и длины строки MOTD.
set -euo pipefail
exec 3<>/dev/tcp/127.0.0.1/25565
printf '\xfe\x01' >&3
[ "$(head -c 3 <&3 | wc -c)" -ge 3 ]
